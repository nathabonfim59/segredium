#!/usr/bin/env node
/**
 * Regenerates docs/api-reference/go/ from the Go source with gomarkdoc.
 *
 * Run `npm run docs:api` after changing exported identifiers or package comments, and commit the
 * result. CI runs this script and fails when the committed pages differ (see docs.yml).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'docs', 'api-reference');
const goDir = join(apiDir, 'go');

const repositoryUrl = 'https://github.com/nathabonfim59/segredium';
const defaultBranch = 'main';
const gomarkdocVersion = 'v1.1.0';
const marker = '<!-- Generated by npm run docs:api. Source of truth: the Go source. Do not edit by hand. -->';

const toPosix = (p) => p.split('\\').join('/');

// Packages of the main module only. e2e/sdkgo is a separate module and has no public API.
function goPackages() {
  const out = execFileSync('go', ['list', '-f', '{{.Dir}}', './...'], { cwd: root, encoding: 'utf-8' });
  return out.split('\n').filter(Boolean).map((dir) => './' + toPosix(relative(root, dir)));
}

function generate() {
  rmSync(apiDir, { recursive: true, force: true });
  mkdirSync(goDir, { recursive: true });
  console.log('Generating Go API reference with gomarkdoc...');
  execFileSync(
    'go',
    [
      'run',
      `github.com/princjef/gomarkdoc/cmd/gomarkdoc@${gomarkdocVersion}`,
      '--repository.url', repositoryUrl,
      '--repository.default-branch', defaultBranch,
      '--repository.path', '/',
      '--output', join(goDir, '{{.Dir}}', 'index.md'),
      ...goPackages(),
    ],
    { cwd: root, stdio: 'inherit' },
  );
}

function packages() {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name === 'index.md' && dir !== goDir) found.push({ path, dir: toPosix(relative(goDir, dir)) });
    }
  };
  walk(goDir);
  return found
    .map((p) => ({ ...p, summary: summary(p.path), ...group(p.dir) }))
    .sort((a, b) => a.dir.localeCompare(b.dir));
}

function group(dir) {
  if (dir.startsWith('cmd/')) return { group: 'Command' };
  if (dir === 'internal/ops') return { group: 'API operations' };
  return { group: 'Packages' };
}

// The first sentence of the package comment, which gomarkdoc prints right after the import block.
function summary(file) {
  const text = readFileSync(file, 'utf-8');
  const after = text.split('```\n\n')[1] ?? '';
  const first = after.split('\n\n')[0] ?? '';
  const text1 = first.replace(/\\(.)/g, '$1').replace(/\s+/g, ' ').trim();
  const end = text1.search(/\.(\s|$)/);
  return end === -1 ? text1 : text1.slice(0, end);
}

function writeIndexes(pkgs) {
  const groups = ['Command', 'API operations', 'Packages'];
  const sections = groups
    .map((name) => {
      const items = pkgs.filter((p) => p.group === name);
      if (!items.length) return '';
      const lines = items.map((p) => `- [\`${p.dir}\`](/api-reference/go/${p.dir}/)${p.summary ? `: ${p.summary}.` : ''}`);
      return `## ${name}\n\n${lines.join('\n')}`;
    })
    .filter(Boolean)
    .join('\n\n');

  writeFileSync(
    join(goDir, 'index.md'),
    `${marker}\n\n# Go API reference\n\nThese pages list the exported identifiers of every Go package in the module \`github.com/nathabonfim59/segredium\`, generated from the source comments by [gomarkdoc](https://github.com/princjef/gomarkdoc). Almost all packages live under \`internal/\`, so other Go modules cannot import them. The pages are for people who read or extend the server. To use segredium from your own code, talk to it with an AWS SDK. See [API compatibility](/compatibility).\n\n${sections}\n`,
  );
  writeFileSync(
    join(apiDir, 'index.md'),
    `${marker}\n\n# API reference\n\n- [Go API reference](/api-reference/go/) lists every package in the server.\n- [API compatibility](/compatibility) lists the Secrets Manager operations the server implements.\n\nRun \`npm run docs:api\` to regenerate these pages.\n`,
  );
}

generate();
const pkgs = packages();
if (!pkgs.length) {
  console.error('gomarkdoc produced no packages');
  process.exit(1);
}
writeIndexes(pkgs);
console.log(`Wrote ${pkgs.length} package pages to ${toPosix(relative(root, goDir))}`);
